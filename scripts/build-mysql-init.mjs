import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { ROOT, readProjectConfig } from "./project-config.mjs";

const check = process.argv.includes("--check");
const config = await readProjectConfig();
const journal = JSON.parse(await readFile(path.join(ROOT, "apps/console/drizzle/meta/_journal.json"), "utf8"));
const fixtures = JSON.parse(await readFile(path.join(ROOT, "fixtures/demo.json"), "utf8"));

const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const migrationRows = [];
const migrations = [];
for (const entry of journal.entries) {
  const relative = `apps/console/drizzle/${entry.tag}.sql`;
  const source = await readFile(path.join(ROOT, relative), "utf8");
  migrations.push(`-- ${relative}\n${source.replaceAll("--> statement-breakpoint", "\n")}`);
  migrationRows.push(`(${sqlString(createHash("sha256").update(source).digest("hex"))}, ${entry.when})`);
}

const productValues = fixtures.products.map((product) => `(${[
  product.sku,
  product.name,
  product.description,
  product.priceCents,
  product.stock,
  product.status,
  product.imageUrl,
].map((value) => typeof value === "number" ? value : sqlString(value)).join(", ")})`).join(",\n  ");
const knowledge = fixtures.knowledge;
const output = `-- Generated by scripts/build-mysql-init.mjs from Drizzle migrations and fixtures/demo.json.\n-- The Console administrator is created separately by pnpm db:seed.\n\nSET NAMES utf8mb4;\nSET time_zone = '+00:00';\nCREATE DATABASE IF NOT EXISTS \`${config.database.name}\` DEFAULT CHARACTER SET utf8mb4 DEFAULT COLLATE utf8mb4_0900_ai_ci;\nUSE \`${config.database.name}\`;\n\nCREATE TABLE IF NOT EXISTS \`__drizzle_migrations\` (\n  \`id\` serial PRIMARY KEY,\n  \`hash\` text NOT NULL,\n  \`created_at\` bigint\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;\n\n${migrations.join("\n\n")}\n\nINSERT INTO \`demo_product\` (\`sku\`, \`name\`, \`description\`, \`price_cents\`, \`stock\`, \`status\`, \`image_url\`) VALUES\n  ${productValues};\n\nINSERT INTO \`knowledge_document\` (\`title\`, \`category\`, \`content\`, \`source\`, \`status\`, \`index_status\`) VALUES (\n  ${sqlString(knowledge.title)}, ${sqlString(knowledge.category)}, ${sqlString(knowledge.content)}, ${sqlString(knowledge.source)}, ${sqlString(knowledge.status)}, 'PENDING'\n);\nSET @knowledge_document_id = LAST_INSERT_ID();\nINSERT INTO \`knowledge_document_version\` (\`document_id\`, \`version\`, \`title\`, \`category\`, \`content\`, \`source\`, \`source_type\`, \`status\`, \`created_by\`)\nSELECT \`id\`, \`version\`, \`title\`, \`category\`, \`content\`, \`source\`, \`source_type\`, \`status\`, 'seed' FROM \`knowledge_document\` WHERE \`id\` = @knowledge_document_id;\nINSERT INTO \`knowledge_index_job\` (\`document_id\`, \`target_version\`, \`requested_by\`)\nVALUES (@knowledge_document_id, 1, 'seed');\n\nINSERT INTO \`__drizzle_migrations\` (\`hash\`, \`created_at\`) VALUES\n  ${migrationRows.join(",\n  ")};\n`;

const target = path.join(ROOT, "sql/mysql-init.sql");
const current = await readFile(target, "utf8").catch(() => "");
if (current !== output) {
  if (check) {
    console.error("sql/mysql-init.sql is stale. Run pnpm db:build-init.");
    process.exit(1);
  }
  await writeFile(target, output, "utf8");
  console.log("Generated sql/mysql-init.sql from migrations and demo fixtures.");
} else {
  console.log("sql/mysql-init.sql is current.");
}
